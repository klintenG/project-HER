"""Generate both browser structural contract and TS types from Pydantic."""
import json
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from agent.editorial.models import Timeline

def export():
    root=Path(__file__).resolve().parents[1]/'remotion/src/editorial'
    schema=Timeline.model_json_schema()
    (root/'schema.json').write_text(json.dumps(schema,indent=2)+'\n')
    def ts(row):
        if '$ref' in row:return row['$ref'].split('/')[-1]
        if 'const' in row:return json.dumps(row['const'])
        if 'enum' in row:return ' | '.join(json.dumps(v) for v in row['enum'])
        if 'anyOf' in row:return ' | '.join(ts(v) for v in row['anyOf'])
        if row.get('type')=='array':return '('+ts(row['items'])+')[]'
        if row.get('type')=='object':return 'Record<string, unknown>'
        return {'integer':'number','number':'number','string':'string','boolean':'boolean','null':'null'}.get(row.get('type'),'unknown')
    out=['// Generated by scripts/export_editorial_schema.py; do not hand-edit.']
    for name,row in {**schema['$defs'],'Timeline':schema}.items():
        out.append('export type '+name+' = {')
        # Pydantic materializes all defaults before crossing the JSON boundary.
        out.extend('  '+k+': '+ts(v)+';' for k,v in row['properties'].items())
        out.append('}')
    (root/'types.ts').write_text('\n'.join(out)+'\n')

if __name__=='__main__':export()
