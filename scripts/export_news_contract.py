"""Regenerate the TypeScript contract from the authoritative Python models."""
import json
from pathlib import Path
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from agent.news_models import Manifest
schema=Manifest.model_json_schema()
def ts(s):
    if '$ref' in s: return s['$ref'].split('/')[-1]
    if 'const' in s: return json.dumps(s['const'])
    if 'enum' in s: return ' | '.join(json.dumps(v) for v in s['enum'])
    if 'anyOf' in s: return ' | '.join(ts(v) for v in s['anyOf'])
    t=s.get('type')
    if t=='array': return 'Array<'+ts(s['items'])+'>'
    if t=='object':
        if 'properties' not in s: return 'Record<string, '+ts(s.get('additionalProperties',{}))+'>'
        return '{\n'+''.join('  '+json.dumps(k)+''+': '+ts(v)+';\n' for k,v in s['properties'].items())+'}'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(t,'unknown')
parts=['// Generated by scripts/export_news_contract.py; do not edit.\n']
for name,s in schema['$defs'].items(): parts.append(f'export type {name} = {ts(s)};\n')
parts.append('export type Manifest = '+ts(schema)+';\n')
parts.append('export const newsJSONSchema = '+json.dumps(schema,ensure_ascii=False,indent=2)+' as const;\n')
Path('remotion/src/news-contract.ts').write_text('\n'.join(parts))
Path('agent/news/manifest.schema.json').write_text(json.dumps(schema,indent=2))
