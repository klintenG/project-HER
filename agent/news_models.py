"""Version 1 News contract. Extra model fields are rejected before rendering."""
from __future__ import annotations

import re
from typing import Literal, Optional
from pydantic import BaseModel, ConfigDict, Field, model_validator


class Model(BaseModel):
    model_config = ConfigDict(extra="forbid", validate_assignment=True)


class NewsError(ValueError):
    def __init__(self, message, status="error", choices=None):
        super().__init__(message)
        self.status, self.choices = status, choices or []

    def response(self):
        return {"status": self.status, "error": str(self), "choices": self.choices}


class Input(Model):
    original: str
    normalized: str
    kind: Literal["source_url", "topic_query", "supplied_account", "mixed"]
    source_policy: Literal["auto", "online", "supplied"] = "auto"
    subject: str
    event_date: Optional[str] = None
    entities: list[str] = Field(default_factory=list)
    places: list[str] = Field(default_factory=list)
    basis: Literal["reported", "user_supplied", "corroborated", "fictional"] = "reported"
    assumptions: list[str] = Field(default_factory=list)


class Source(Model):
    id: str
    url: Optional[str] = None
    title: str
    retrieved_at: str
    published_at: Optional[str] = None
    updated_at: Optional[str] = None
    event_date: Optional[str] = None
    authors: list[str] = Field(default_factory=list)
    text: str
    canonical_url: Optional[str] = None


class Claim(Model):
    id: str
    source_ids: list[str] = Field(min_length=1)
    text: str
    excerpts: dict[str, str]


class Evidence(Model):
    sources: list[Source]
    claims: list[Claim]
    conflicts: list[str] = Field(default_factory=list)
    unresolved: list[str] = Field(default_factory=list)
    verification: Literal["single_source", "multiple_accounts", "user_supplied", "fictional", "conflicting"]

    @model_validator(mode="after")
    def links(self):
        sources = {s.id: s for s in self.sources}
        if len(sources) != len(self.sources) or len({c.id for c in self.claims}) != len(self.claims):
            raise ValueError("Duplicate evidence IDs")
        for claim in self.claims:
            for sid in claim.source_ids:
                quote = claim.excerpts.get(sid, "")
                if sid not in sources or not quote.strip() or quote not in sources[sid].text:
                    raise ValueError("Claim excerpt must occur verbatim in its source")
        return self


class Entity(Model):
    id: str
    name: str
    kind: Literal["person", "animal", "object", "building", "place", "symbol"]
    description: str
    identity: Literal["generic", "real", "fictional"] = "generic"
    reference_query: Optional[str] = None
    # Exact geometry must come from an audited local asset, never generated by AI.
    exact_asset: Optional[str] = None

    @property
    def is_group(self):
        """Only explicit human groups may contain several foreground silhouettes."""
        return self.kind == "person" and bool(
            # Group context behind a named individual does not make their
            # portrait a representative group (e.g. a commander with troops).
            re.search(r"^(?:(?:a|an|the|one|two|three|compact|small|representative|isolated)\s+)*(?:group of|team of|crowd of|athletes|players|people|persons)\b", self.description, re.I)
            or re.search(r"\b(team|crew|forces|troops|soldiers|army|armies|police|sailors|warriors|rebels|villagers|protesters|workers)\s*$", self.name, re.I))

    @property
    def is_portrait(self):
        return self.kind=='person' and not self.is_group and bool(
            re.search(r'portrait|upper[ -]body|bust|head[ -]shot|waist[ -]up',self.description,re.I)
            and not re.search(r'full[ -]body',self.description,re.I))


class Sentence(Model):
    id: str
    text: str = Field(min_length=1)
    claim_ids: list[str] = Field(min_length=1)
    entity_ids: list[str] = Field(default_factory=list, max_length=3)
    phrase: str = Field(min_length=1)
    role: Literal["hook", "context", "development", "meaning", "close"]
    emphasis: list[str] = Field(default_factory=list)
    headline_text: Optional[str] = None


class Script(Model):
    summary: str
    narration: str
    sentences: list[Sentence] = Field(min_length=1, max_length=24)
    entities: list[Entity] = Field(default_factory=list, max_length=24)

    @model_validator(mode="after")
    def links(self):
        eids = {e.id for e in self.entities}
        if len(eids) != len(self.entities) or len({s.id for s in self.sentences}) != len(self.sentences):
            raise ValueError("Duplicate script IDs")
        for s in self.sentences:
            if not s.text.strip() or not s.phrase.strip(): raise ValueError("Empty News sentence/phrase")
            if not set(s.entity_ids) <= eids:
                raise ValueError("Unknown sentence entity")
        if eids != {e for s in self.sentences for e in s.entity_ids}:
            raise ValueError("Unused or missing concrete visual entity")
        if self.narration != " ".join(s.text for s in self.sentences):
            raise ValueError("Narration must equal joined sentences")
        return self


class Boundary(Model):
    sentence_id: str
    text: str
    start: float = Field(ge=0)
    end: float = Field(gt=0)


class Audio(Model):
    path: str
    duration: float = Field(gt=0)
    method: Literal["native_words", "sentence_clips", "mixed"]
    quality: str
    script_hash: str
    phrases: list[Boundary]
    words: list[Boundary] = Field(default_factory=list)
    provider: str = ""
    model: Optional[str] = None
    fallbacks: list[str] = Field(default_factory=list)


class Asset(Model):
    id: str
    entity_id: str
    path: str
    raw_path: str
    prompt: str
    provider: str
    source_url: Optional[str] = None
    license: Optional[str] = None
    attribution: Optional[str] = None
    reference_url: Optional[str] = None
    reference_entity: Optional[str] = None
    image_model: Optional[str] = None
    origin: Literal["generated", "photo", "reference_edit", "verified_local"] = "generated"
    identity_verified: bool = False
    illustrative: bool = True
    source_basis: str
    segmentation: str
    mask: dict[str, float]
    qa: Literal["passed", "degraded"] = "passed"
    fallback: Optional[str] = None


class Rect(Model):
    x: float = Field(ge=0, le=1)
    y: float = Field(ge=0.2, le=0.85)
    w: float = Field(gt=0, le=0.84)
    h: float = Field(gt=0, le=0.65)

    @model_validator(mode="after")
    def safe(self):
        if self.x < .08 - 1e-6 or self.x+self.w > .92+1e-6 or self.y+self.h > .85+1e-6:
            raise ValueError("Foreground outside News safe region")
        return self


class Text(Model):
    id: str
    text: str
    lines: list[str]
    rect: Rect
    size: float = Field(ge=14, le=100)  # size in pixels at 1080 width
    weight: Literal[600, 700] = 600
    reveal_frames: list[int]
    emphasis: list[str] = Field(default_factory=list)


class Layer(Model):
    id: str
    asset_id: str
    entity_id: str
    rect: Rect
    z: int = Field(ge=0, le=10)
    reveal: int = Field(ge=0)
    exit: int = Field(gt=0)
    opacity: float = Field(default=1, gt=0, le=1)
    persist: bool = False
    portrait_fade: bool = False
    overlap: Literal["none", "context"] = "none"


Template = Literal["single_subject", "two_subjects", "person_two_objects", "subject_context", "text_bridge", "place_object_stack"]


class Beat(Model):
    id: str
    start: int = Field(ge=0)
    end: int = Field(gt=0)
    sentence_ids: list[str]
    template: Template
    texts: list[Text]
    layers: list[Layer] = Field(max_length=3)


class Event(Model):
    kind: Literal["reveal", "emphasize", "move", "persist", "replace", "exit"]
    frame: int = Field(ge=0)
    target: str


class Theme(Model):
    paper: str = "#F2F0EC"
    center: str = "#FAF9F6"
    edge: str = "#DDDAD4"
    text: str = "#505050"
    secondary: str = "#686868"
    font_semibold: str
    font_bold: str
    transition_frames: int = Field(default=10, ge=8, le=14)
    branding: str = ""


class Manifest(Model):
    schema_version: Literal["1.0"] = "1.0"
    content_mode: Literal["news"] = "news"
    generation_id: str = Field(pattern=r"^[A-Za-z0-9_-]{1,80}$")
    width: int = Field(gt=0)
    height: int = Field(gt=0)
    fps: int = Field(ge=1, le=60)
    duration_frames: int = Field(gt=0)
    seed: int = 42
    theme: Theme
    input: Input
    evidence: Evidence
    script: Script
    audio: Audio
    assets: list[Asset]
    beats: list[Beat]
    events: list[Event]
    warnings: list[str] = Field(default_factory=list)
    stage_timings: dict[str, float] = Field(default_factory=dict)
    outputs: dict[str, str] = Field(default_factory=dict)

    @model_validator(mode="after")
    def coherent(self):
        import hashlib
        import math
        if self.audio.script_hash != hashlib.sha256(self.script.narration.encode()).hexdigest():
            raise ValueError("Stale audio alignment")
        if not math.isfinite(self.audio.duration) or abs(self.duration_frames/self.fps-self.audio.duration) > 1/self.fps+.001:
            raise ValueError("Audio and video duration differ")
        cids = {c.id for c in self.evidence.claims}
        sids = {s.id for s in self.script.sentences}
        eids = {e.id for e in self.script.entities}
        assets = {a.id: a for a in self.assets}
        if len(assets) != len(self.assets):
            raise ValueError("Duplicate assets")
        for a in self.assets:
            if a.entity_id not in eids:
                raise ValueError("Unknown asset entity")
            entity=next(e for e in self.script.entities if e.id==a.entity_id)
            if a.origin=='photo' and (entity.identity!='real' or a.illustrative or not a.identity_verified or
                    not all((a.source_url,a.reference_entity,a.license,a.attribution))):
                raise ValueError("Actual reference photos require real identity and source attribution")
            if a.origin=='reference_edit' and (not a.illustrative or a.identity_verified or not all((a.reference_url,a.image_model))):
                raise ValueError("Reference edits must retain provenance and remain marked illustrative")
        for s in self.script.sentences:
            if not set(s.claim_ids) <= cids:
                raise ValueError("Unlinked factual sentence")
        for boundaries in (self.audio.phrases, self.audio.words):
            previous = 0
            for b in boundaries:
                if b.sentence_id not in sids or b.start < previous-.001 or b.end <= b.start or b.end > self.audio.duration+.05:
                    raise ValueError("Invalid audio boundaries")
                previous = b.end
        previous, targets, covered = 0, set(), set()
        for beat in self.beats:
            if beat.start != previous or beat.end <= beat.start or beat.end > self.duration_frames:
                raise ValueError("Beats must tile the audio timeline")
            if not set(beat.sentence_ids) <= sids:
                raise ValueError("Unknown beat sentence")
            represented = {l.entity_id for l in beat.layers}
            required = {e for s in self.script.sentences if s.id in beat.sentence_ids for e in s.entity_ids}
            if not required <= represented:
                raise ValueError("Missing essential visual subject")
            covered.update(beat.sentence_ids)
            for layer in beat.layers:
                if layer.asset_id not in assets or assets[layer.asset_id].entity_id != layer.entity_id:
                    raise ValueError("Invalid layer asset reference")
                if not beat.start <= layer.reveal < layer.exit <= self.duration_frames or layer.exit < beat.end:
                    raise ValueError("Invalid layer timing")
                if layer.overlap == "context" and (layer.opacity > .25 or assets[layer.asset_id].provider != "verified_local"):
                    raise ValueError("Context geometry must be quiet and come from an audited asset")
                targets.add(layer.id)
            rectangles = [t.rect for t in beat.texts]+[l.rect for l in beat.layers if l.overlap == "none"]
            for i,a in enumerate(rectangles):
                for b in rectangles[i+1:]:
                    if min(a.x+a.w,b.x+b.w)-max(a.x,b.x) > .001 and min(a.y+a.h,b.y+b.h)-max(a.y,b.y) > .001:
                        raise ValueError("Unintentional foreground collision")
            for t in beat.texts:
                if " ".join(t.lines) != t.text or t.size*self.width/1080 < 28*min(self.width,self.height)/1080:
                    raise ValueError("Text is malformed or too small")
                if any(f2 < f1 for f1,f2 in zip(t.reveal_frames,t.reveal_frames[1:])):
                    raise ValueError("Text reveal order must follow phrase order")
                if len(t.reveal_frames) != len(t.text.split()) or not all(beat.start <= f < beat.end for f in t.reveal_frames):
                    raise ValueError("Invalid text reveal anchors")
                targets.add(t.id)
            previous = beat.end
        if previous != self.duration_frames or covered != sids:
            raise ValueError("Incomplete storyboard")
        if any(e.target not in targets or e.frame >= self.duration_frames for e in self.events):
            raise ValueError("Invalid event target/timing")
        return self
